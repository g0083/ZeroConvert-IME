// Generates the Android emoji palette catalog from the pinned Unicode data.
//
// Source of truth: data/emoji/emoji-test-15.1.txt (Unicode License v3, CLDR order).
// Japanese keywords come from the bundled azooKey emoji dictionary that the
// conversion engine already loads, so the palette and the conversion dictionary
// describe the same emoji set.
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const SOURCE = 'data/emoji/emoji-test-15.1.txt';
const KEYWORDS = 'android/app/src/main/assets/emoji_all_E15.1.txt';
const OUTPUT = 'android/app/src/main/assets/emoji_catalog.tsv';

const SKIN_TONES = [0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff];
const VS16 = '\ufe0f';

/** Groups kept in the palette, in CLDR order. `Component` is not user-facing. */
const GROUPS = [
  ['smileys', '笑顔', '😀'],
  ['people', '人・体', '👋'],
  ['nature', '動物・自然', '🐻'],
  ['food', '食べ物', '🍔'],
  ['travel', '旅行', '✈️'],
  ['activities', 'スポーツ', '⚽'],
  ['objects', '物', '💡'],
  ['symbols', '記号', '❤️'],
  ['flags', '旗', '🏳️']
];
const GROUP_IDS = new Map(GROUPS.map(([id], index) => [index, id]));
const UNICODE_GROUP_ORDER = [
  'Smileys & Emotion',
  'People & Body',
  'Animals & Nature',
  'Food & Drink',
  'Travel & Places',
  'Activities',
  'Objects',
  'Symbols',
  'Flags'
];

const stripTone = text => [...text].filter(ch => !SKIN_TONES.includes(ch.codePointAt(0))).join('');
const tonesOf = text => [...text].filter(ch => SKIN_TONES.includes(ch.codePointAt(0))).map(ch => ch.codePointAt(0));

function parseUnicode(text) {
  const groups = new Map();
  const names = new Map();
  let group = null;
  for (const raw of text.split(/\r?\n/)) {
    if (raw.startsWith('# group:')) {
      group = raw.slice('# group:'.length).trim();
      groups.set(group, []);
    } else if (raw.startsWith('# subgroup:') || raw.startsWith('#') || !raw.trim()) {
      continue;
    } else if (group) {
      const [codePoints, rest] = raw.split(';');
      if (rest.split('#')[0].trim() !== 'fully-qualified') continue;
      const emoji = String.fromCodePoint(...codePoints.trim().split(/\s+/).map(hex => parseInt(hex, 16)));
      groups.get(group).push(emoji);
      // The trailing comment is "<E1.0> name"; keep the name for English search.
      const name = rest.split('#')[1]?.replace(/^\s*E[\d.]+\s+/, '').trim();
      if (name) names.set(emoji, name);
    }
  }
  return { groups, names };
}

function parseKeywords(text) {
  const keywords = new Map();
  for (const line of text.split(/\r?\n/)) {
    const [emoji, list] = line.split('\t');
    if (!emoji || !list) continue;
    keywords.set(emoji.trim().replaceAll(VS16, ''), list.split(',').map(word => word.trim()).filter(Boolean));
  }
  return keywords;
}

const { groups: unicode, names } = parseUnicode(await readFile(new URL(SOURCE, root), 'utf8'));
const keywords = parseKeywords(await readFile(new URL(KEYWORDS, root), 'utf8'));

const rows = [];
const seen = new Set();
let toneCount = 0;
for (const [index, groupName] of UNICODE_GROUP_ORDER.entries()) {
  const entries = unicode.get(groupName);
  if (!entries) throw new Error(`Missing Unicode group: ${groupName}`);
  // Group skin-tone variants under their base emoji so the palette shows one cell
  // per emoji and offers the tones from a long press.
  const byBase = new Map();
  for (const emoji of entries) {
    const base = stripTone(emoji);
    if (!byBase.has(base)) byBase.set(base, []);
    byBase.get(base).push(emoji);
  }
  for (const [base, variants] of byBase) {
    if (seen.has(base)) continue;
    seen.add(base);
    const tones = variants.filter(emoji => {
      const applied = tonesOf(emoji);
      return applied.length > 0 && new Set(applied).size === 1;
    });
    const toneList = tones.length === 5 ? tones : [];
    if (toneList.length > 0) toneCount += 1;
    const words = keywords.get(base.replaceAll(VS16, '')) ?? [];
    // Fall back to the Unicode English name so every emoji stays searchable.
    const searchable = words.length > 0 ? words : [names.get(base) ?? names.get(variants[0]) ?? ''].filter(Boolean);
    rows.push([
      GROUP_IDS.get(index),
      base,
      searchable.slice(0, 6).join(','),
      toneList.join('|')
    ].join('\t'));
  }
}

const header = [
  '# Generated by scripts/generate-android-emoji-catalog.mjs. Do not edit.',
  `# Source: ${SOURCE} (Unicode License v3). Keywords: azooKey emoji dictionary.`,
  '# group\temoji\tkeywords\tskin-tone variants'
].join('\n');
const output = `${header}\n${rows.join('\n')}\n`;
const url = new URL(OUTPUT, root);
if (process.argv.includes('--check')) {
  if (await readFile(url, 'utf8') !== output) throw new Error(`Stale generated file: ${OUTPUT}`);
} else {
  await mkdir(new URL('.', url), { recursive: true });
  await writeFile(url, output, 'utf8');
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${rows.length} emoji ` +
  `(${toneCount} with skin tones) across ${UNICODE_GROUP_ORDER.length} categories`);
