import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const main = await readFile(new URL('windows/crates/server/src/ai_assist/mod.rs', root), 'utf8');
const variant = await readFile(new URL('windows/crates/server/src/ai_assist/typo_variant.rs', root), 'utf8');
function pairs(text, name) {
  const block = text.match(new RegExp(`const ${name}: [\\s\\S]*?= &\\[([\\s\\S]*?)\\];`));
  if (!block) throw new Error(`Cannot find ${name}`);
  return [...block[1].matchAll(/\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)/g)]
    .map(match => [JSON.parse(`"${match[1]}"`), JSON.parse(`"${match[2]}"`)]);
}
const standard = pairs(main, 'STANDARD_VOCAB');
const proper = pairs(variant, 'PROPER_NOUN_VOCAB');
const embedded = (await readFile(new URL('windows/crates/server/src/ai_assist/builtin_vocab.tsv', root), 'utf8'))
  .split(/\r?\n/).filter(line => line.includes('\t')).map(line => line.split('\t').slice(0, 2));
const index = new Map();
for (const [reading, surface] of [...standard, ...proper, ...embedded]) {
  if (reading && surface && !index.has(reading)) index.set(reading, surface);
}
const clean = new Set(standard.map(([reading]) => reading));
const lines = ['# Generated by scripts/generate-android-assist-vocabulary.mjs from Windows assist sources.'];
for (const [reading, surface] of index) lines.push(`${reading}\t${surface}\t${clean.has(reading) ? 'standard' : 'index'}`);
const output = new URL('android/app/src/main/assets/assist-vocabulary.tsv', root);
const generated = lines.join('\n') + '\n';
const quote = value => JSON.stringify(value).replaceAll('$', '\\$');
const kotlinMap = entries => entries.map(([key, value]) => `        ${quote(key)} to ${quote(value)}`).join(',\n');
const romajiBlock = main.match(/fn hiragana_to_romaji[\s\S]*?match c \{([\s\S]*?)\n    \}/)?.[1];
if (!romajiBlock) throw new Error('Cannot find hiragana_to_romaji');
const romaji = [...romajiBlock.matchAll(/'([^']+)' => "([^"]+)"/g)].map(m => [m[1], m[2]]);
const ruleOutput = new URL('android/app/src/main/java/com/zeroconvert/ime/assist/WindowsTypoData.kt', root);
const rules = pairs(main, 'TYPO_TABLE');
const kotlin = `// Generated by scripts/generate-android-assist-vocabulary.mjs. Do not edit by hand.
package com.zeroconvert.ime.assist

internal object WindowsTypoData {
    val standard: Map<String, String> = linkedMapOf(
${kotlinMap(standard)}
    )
    val rules: Map<String, String> = linkedMapOf(
${kotlinMap(rules)}
    )
    val romaji: Map<String, String> = mapOf(
${kotlinMap(romaji)}
    )
}
`;
for (const [path, content] of [[output, generated], [ruleOutput, kotlin]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated file: ${fileURLToPath(path)}`);
  } else await writeFile(path, content, 'utf8');
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${index.size} readings, ${clean.size} standard, ${rules.length} typo rules`);
