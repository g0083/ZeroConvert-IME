import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { parseTsv } from '../windows/scripts/validate-keyboard-typo-dictionary.mjs';
import { lookupReadings, scoreFor } from '../windows/scripts/generate-keyboard-typo-dictionary-swift.mjs';
const root = new URL('../', import.meta.url);
const rows = parseTsv(await readFile(new URL('windows/data/keyboard-typo-dictionary.tsv', root), 'utf8'));
const entries = rows.flatMap(row => lookupReadings(row).map(reading =>
  `    {${JSON.stringify(row.expected_candidate)}, ${JSON.stringify(reading)}, ${scoreFor(row)}f, ${row.reference_lcid}, ${row.reference_rcid}, ${row.reference_mid}, {}, 3}`));
const generated = `// Generated by scripts/generate-android-keyboard-typos.mjs. Do not edit.
// Derived selection data: CC BY-SA 3.0. See bundled NOTICE-keyboard-typo-dictionary.md.
static const std::vector<DicdataElement> keyboardTypoEntries = {
${entries.join(',\n')}
};
`;
const outputs = [['android/app/src/main/cpp/keyboard_typo_dictionary.inc', generated]];
outputs.push(['android/app/src/androidTest/assets/keyboard-typo-cases.tsv',
  '# Generated from Windows keyboard typo selections. CC BY-SA 3.0; see bundled NOTICE.\n' +
  rows.flatMap(row => lookupReadings(row).map(reading =>
    [reading, row.expected_candidate, row.reference_lcid, row.reference_rcid, row.reference_mid, scoreFor(row)].join('\t'))).join('\n') + '\n']);
for (const kind of ['dictionary', 'rewrite']) outputs.push([
  `android/app/src/main/assets/NOTICE-keyboard-typo-${kind}.md`,
  await readFile(new URL(`windows/data/keyboard-typo-${kind}-NOTICE.md`, root), 'utf8')
]);
for (const [path, content] of outputs) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Stale generated file: ${path}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content, 'utf8');
  }
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${rows.length} selections / ${entries.length} dictionary entries and notices`);
