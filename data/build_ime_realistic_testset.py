def _mask_digits(text: str) -> str:
    return DIGIT_RUN_RE.sub("nam", text)


def validate_cases(cases: list[dict]) -> None:
    if len(cases) != 160:
        raise AssertionError(f"Expected 160 cases, got {len(cases)}")
    cat_counts: dict[str, int] = {}
    seen_pairs: set[tuple[str, str]] = set()
    ime_keys: set[str] = set()
    for c in cases:
        cat = c["category"]
        cat_counts[cat] = cat_counts.get(cat, 0) + 1
        tlen = len(c["target"])
        if not (4 <= tlen <= 20):
            raise AssertionError(f"Target length out of [4, 20]: id={c['id']} len={tlen} target={c['target']!r}")
        if "nam" in c["target"].lower():
            raise AssertionError(f"Literal 'nam' in raw target: id={c['id']} target={c['target']!r}")
        pair = (c["left_context"], c["target"])
        if pair in seen_pairs:
            raise AssertionError(f"Duplicate (left_context, target): {pair}")
        seen_pairs.add(pair)
        ime_keys.update(source_keys(c))
        ime_keys.update(source_keys({**c, "target": _mask_digits(c["target"]), "expected": _mask_digits(c["expected"])}))

    if len(cat_counts) != 8 or any(cnt != 20 for cnt in cat_counts.values()):
        raise AssertionError(f"Unexpected category distribution: {cat_counts}")

    reserved_eval_keys: set[str] = set()
    for path in EVALUATION_FILES:
        if path.exists() and path.resolve() != OUT_PATH.resolve():
            for row in load_jsonl(path):
                reserved_eval_keys.update(source_keys(row))

    train_val_keys: set[str] = set()
    for path in (TRAIN_PATH, VAL_PATH):
        if not path.exists():
            raise FileNotFoundError(f"Missing required dataset split: {path}")
        for row in load_jsonl(path):
            train_val_keys.update(source_keys(row))
            if row.get("completion"):
                train_val_keys.add(normalize(row["completion"]))

    eval_overlap = sorted(ime_keys & reserved_eval_keys)
    train_overlap = sorted(ime_keys & train_val_keys)
    if eval_overlap or train_overlap:
        raise AssertionError(
            f"Leakage/overlap detected! eval_overlap={eval_overlap}, train_overlap={train_overlap}"
        )


def main():
    cases = build_cases()
    validate_cases(cases)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PATH.open("w", encoding="utf-8", newline="\n") as f:
        for c in cases:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    lengths = [len(c["target"]) for c in cases]
    print(
        f"Wrote {len(cases)} cases to {OUT_PATH} "
        f"(len min={min(lengths)}, max={max(lengths)}, avg={sum(lengths)/len(lengths):.1f}, leakage=0)"
    )


if __name__ == "__main__":
    main()
