def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "artifacts/datasets/standard-v3-knowledge")
    parser.add_argument("--val-fraction", type=float, default=0.08)
    args = parser.parse_args()

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Loading evaluation keys from {len(EVALUATION_FILES)} benchmark files...")
    reserved_keys = evaluation_keys(EVALUATION_FILES)
    print(f"Reserved evaluation keys: {len(reserved_keys)}")

    raw_rows = collect_raw_rows(reserved_keys)
    print(f"Collected raw candidate rows: {len(raw_rows)}")

    train_rows, val_rows, excluded_rows = separated_rows(
        raw_rows,
        reserved=reserved_keys,
        val_fraction=args.val_fraction,
        seed="20261029_argon4_std_v3",
    )

    print(f"\nSeparation results:")
    print(f"  - Train rows: {len(train_rows)}")
    print(f"  - Val rows:   {len(val_rows)}")
    print(f"  - Excluded (leakage protection): {len(excluded_rows)}")
    print(f"  - Train category breakdown: {dict(Counter(r['category'] for r in train_rows))}")

    validate_rows(train_rows, val_rows, reserved_keys)
    print("Isolation validation PASSED: zero leak keys, zero split overlap.")

    train_path = out_dir / "train.jsonl"
    val_path = out_dir / "val.jsonl"

    with train_path.open("w", encoding="utf-8") as f:
        for r in train_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    with val_path.open("w", encoding="utf-8") as f:
        for r in val_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    manifest = {
        "policy": POLICY,
        "evaluation": {
            p.relative_to(ROOT).as_posix(): {
                "sha256": sha256(p),
                "count": len(load_jsonl(p)),
            }
            for p in EVALUATION_FILES
        },
        "outputs": {
            "train.jsonl": {"sha256": sha256(train_path), "count": len(train_rows)},
            "val.jsonl": {"sha256": sha256(val_path), "count": len(val_rows)},
        },
    }

    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nSaved dataset to: {out_dir}")
    print(f"Manifest written: {manifest_path}")


if __name__ == "__main__":
    main()
