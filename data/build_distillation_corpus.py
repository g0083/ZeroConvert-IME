def generate_samples():
    samples = []

    # 1. 同音異義語・文脈パターン
    for exp, reading, contexts in HOMOPHONE_GROUPS:
        kata_reading = hira_to_kata(reading)
        for ctx in contexts:
            if (ctx, kata_reading) not in TEST_CASES:
                samples.append({
                    "left_context": ctx,
                    "target": reading,
                    "kata": kata_reading,
                    "expected": exp
                })
        # 文脈なし（単体）も追加
        if ("", kata_reading) not in TEST_CASES:
            samples.append({
                "left_context": "",
                "target": reading,
                "kata": kata_reading,
                "expected": exp
            })

    # 2. 辞書単語（単体および修飾付き文脈）
    for w in DICT_WORDS:
        reading_kata = kanji_to_kata(w)
        # 文脈なし単体
        if ("", reading_kata) not in TEST_CASES:
            samples.append({
                "left_context": "",
                "target": reading_kata,
                "kata": reading_kata,
                "expected": w
            })
        # 修飾文脈つき
        for pfx in random.sample(CONTEXT_PREFIXES, 4):
            if pfx and (pfx, reading_kata) not in TEST_CASES:
                samples.append({
                    "left_context": pfx,
                    "target": reading_kata,
                    "kata": reading_kata,
                    "expected": w
                })

    # 3. 口語・補完禁止パターン
    NO_CORRECT = [
        "こんにちわ", "よろしくおねがいしまｓ", "ありがと", "おｋ", "あざす",
        "わら", "草", "りょ", "おつかれー", "了解ですー", "なるほどです",
        "草生える", "わかりみ", "まじで", "それな", "うぽつ", "わこつ"
    ]
    for nc in NO_CORRECT:
        kata = hira_to_kata(nc)
        if ("", kata) not in TEST_CASES:
            samples.append({
                "left_context": "",
                "target": nc,
                "kata": kata,
                "expected": nc
            })

    return samples

if __name__ == "__main__":
    raw_samples = generate_samples()
    print(f"Generated {len(raw_samples)} candidate samples before distillation.")
    with open("data/distill_candidates.json", "w", encoding="utf-8") as f:
        json.dump(raw_samples, f, ensure_ascii=False, indent=2)
    print("Saved candidates to data/distill_candidates.json")
